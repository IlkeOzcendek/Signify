def _report_fonts():
    """Return fonts that support Turkish characters when available."""

    candidates = [ # Regular and bold font-file pairs checked in order
        (
            Path("/System/Library/Fonts/Supplemental/Arial.ttf"),
            Path("/System/Library/Fonts/Supplemental/Arial Bold.ttf"),
        ),
        (
            Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
            Path("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
        ),
    ]

    for regular_path, bold_path in candidates:
        if regular_path.exists() and bold_path.exists():
            if "Signify-Regular" not in pdfmetrics.getRegisteredFontNames():
                pdfmetrics.registerFont(TTFont("Signify-Regular", str(regular_path))) # Registers a local TrueType font under an internal PDF name
                pdfmetrics.registerFont(TTFont("Signify-Bold", str(bold_path)))

            return "Signify-Regular", "Signify-Bold"

    return "Helvetica", "Helvetica-Bold"


