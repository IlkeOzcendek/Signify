def create_verification_report(
    person_name,
    result,
    confidence,
    distance,
    threshold,
    best_reference = None,
    compared_count = None,
    language = "tr",
    engine = "general",
):
    buffer = BytesIO() # In-memory binary stream ------> PDF can be downloaded without creating a disk file
    text = REPORT_TEXT.get(language, REPORT_TEXT["tr"]) # Uses Turkish as fallback when the language code is unknown
    regular_font, bold_font = _report_fonts() # Font names used by ReportLab

    pdf = canvas.Canvas(buffer, pagesize = A4) # Canvas = Page where text and shapes are drawn
    width, height = A4 # A4 dimensions measured in PDF points

    y = height - 60 # y = Current vertical writing position measured from the bottom of the page

    pdf.setFont(bold_font, 24)
    pdf.drawString(50, y, "Signify")
    y -= 30

    pdf.setFont(regular_font, 12)
    pdf.drawString(50, y, text["subtitle"])
    y -= 50

    pdf.setFont(bold_font, 14)
    pdf.drawString(50, y, text["summary"])
    y -= 30

    pdf.setFont(regular_font, 11)

    engine_details = {
        "general": {
            "name": "General v1",
            "model": "Siamese CNN",
            "dataset": (
                "CEDAR + seçili UTSig örnekleri"
                if language == "tr" else "CEDAR + selected UTSig samples"
            ),
        },
        "archive": {
            "name": "Düşük çözünürlüklü tarama v2" if language == "tr" else "Low-resolution scan v2",
            "model": "MobileNetV3 encoder + dual pair heads",
            "dataset": "Arşiv imza koleksiyonu" if language == "tr" else "Archive signature collection",
        },
        "utsig": {
            "name": "Yüksek çözünürlüklü mono v3" if language == "tr" else "High-resolution mono v3",
            "model": "MobileNetV3 encoder + UTSig pair head",
            "dataset": (
                "UTSig (kişi ayrımlı kalibrasyon)"
                if language == "tr" else "UTSig (person-held-out calibration)"
            ),
        },
    }.get(engine, {
        "name": str(engine or "Unknown"),
        "model": "Signature verification ensemble",
        "dataset": "Multiple signature sources",
    })

    report_data = [ # Label-value rows printed inside the verification summary
        (text["date"], datetime.now().strftime("%Y-%m-%d %H:%M:%S")),
        (text["person"], person_name),
        (text["result"], text.get(result, result)),
        (text["confidence"], f"{confidence:.1f}%"),
        (text["distance"], f"{distance:.4f}"),
        (text["threshold"], f"{threshold:.2f}"),
        (text["engine"], engine_details["name"]),
        (text["model"], engine_details["model"]),
        (text["dataset"], engine_details["dataset"]),
    ]

    if best_reference is not None:
        report_data.append((text["best_reference"], best_reference))

    if compared_count is not None:
        report_data.append((text["compared_references"], str(compared_count)))

    for label, value in report_data:
        pdf.setFont(bold_font, 11)
        pdf.drawString(50, y, f"{label}:")
        pdf.setFont(regular_font, 11)
        pdf.drawString(240, y, str(value))
        y -= 24 # Moves the next row downward by 24 PDF points

    y -= 20

    pdf.setFont(bold_font, 12)
    pdf.drawString(50, y, text["interpretation"])
    y -= 25

    pdf.setFont(regular_font, 10)

    if result == "Genuine":
        interpretation = text["genuine_text"]
    elif result == "Uncertain":
        interpretation = text["uncertain_text"]
    else:
        interpretation = text["forgery_text"]

    for line in textwrap.wrap(interpretation, width=95, break_long_words=False):
        pdf.drawString(50, y, line)
        y -= 18

    pdf.setFont(regular_font, 9)
    pdf.drawString(50, 50, text["footer"])

    pdf.save() # Finalizes the PDF content inside the memory buffer

    buffer.seek(0) # Moves the read position back to the beginning before returning the PDF

    return buffer
